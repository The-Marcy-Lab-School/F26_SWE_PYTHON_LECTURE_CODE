name = "Ada"
age = 36

print("name:", name, "age:", age)
# Output: name: Ada age: 36

# sep goes between the values, and end goes after the last value
print("a", "b", "c", sep="-")
# Output: a-b-c

print("loading", end="")
print("...", end="")
print("done")
# Output: loading...done

