age = 22
school = "Marcy Lab School"
train = "D"
pronoun = "his"
subject = "coding"
borough = "The Bronx"

print("Story time!")
print(f"This is a story about {name}.")
print(f"{name} is a {age}-year-old student at {school}.")
print(f"Every day, {name} takes the {train} train from {borough} to {school}.")
